// Command new-plugin scaffolds an official compile-time plugin: directory,
// plugin.go, optional migration, registration in plugins/all/all.go, and
// optional frontend page + page-map + locale placeholders.
//
//	go run ./cmd/new-plugin -id demo [-name "演示"] [-with-frontend] [-with-migration]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"unicode"

	"dragz-admin/backend/internal/plugin"
)

func main() {
	id := flag.String("id", "", "plugin id (required), must match ^[a-z][a-z0-9]{2,15}$")
	name := flag.String("name", "", "display name (default: derived from id)")
	withFrontend := flag.Bool("with-frontend", false, "also scaffold frontend page, page-map entry, and i18n keys")
	withMigration := flag.Bool("with-migration", false, "embed migrations/001_init.sql and implement Migrator")
	flag.Parse()

	if err := run(*id, *name, *withFrontend, *withMigration); err != nil {
		fmt.Fprintf(os.Stderr, "new-plugin: %v\n", err)
		os.Exit(1)
	}
}

func run(id, name string, withFrontend, withMigration bool) error {
	id = strings.TrimSpace(id)
	if !plugin.ValidID(id) {
		return fmt.Errorf("invalid id %q (want ^[a-z][a-z0-9]{2,15}$)", id)
	}
	if name == "" {
		name = titleFromID(id)
	}

	backendRoot, err := findBackendRoot()
	if err != nil {
		return err
	}
	repoRoot := filepath.Dir(backendRoot)

	pluginDir := filepath.Join(backendRoot, "plugins", id)
	if _, err := os.Stat(pluginDir); err == nil {
		return fmt.Errorf("plugin directory already exists: %s", pluginDir)
	} else if !os.IsNotExist(err) {
		return err
	}

	if err := os.MkdirAll(pluginDir, 0o755); err != nil {
		return err
	}

	table := "sys_" + id + "_item"
	pageCode := id + "_page"
	component := "/" + id + "/index"
	exportName := exportNameFromID(id)

	pluginSrc := renderPluginGo(id, name, pageCode, component, table, withMigration)
	if err := os.WriteFile(filepath.Join(pluginDir, "plugin.go"), []byte(pluginSrc), 0o644); err != nil {
		return err
	}

	if withMigration {
		migDir := filepath.Join(pluginDir, "migrations")
		if err := os.MkdirAll(migDir, 0o755); err != nil {
			return err
		}
		sql := fmt.Sprintf("-- %s bootstrap table (optional; edit or add files as needed)\nCREATE TABLE IF NOT EXISTS %s (\n  id BIGSERIAL PRIMARY KEY,\n  name TEXT NOT NULL DEFAULT '',\n  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()\n);\n", id, table)
		if err := os.WriteFile(filepath.Join(migDir, "001_init.sql"), []byte(sql), 0o644); err != nil {
			return err
		}
	}

	if err := patchAllGo(filepath.Join(backendRoot, "plugins", "all", "all.go"), id); err != nil {
		return err
	}

	if withFrontend {
		if err := scaffoldFrontend(repoRoot, id, exportName, component, name); err != nil {
			return err
		}
	}

	fmt.Printf("new-plugin: created plugins/%s (registered in plugins/all/all.go)\n", id)
	if withFrontend {
		fmt.Printf("new-plugin: frontend page + page-map + i18n placeholders for %s\n", component)
	} else {
		fmt.Printf("new-plugin: warning: Meta.Menus Component %q needs a page-map entry (pass -with-frontend or add it manually)\n", component)
	}
	fmt.Println("new-plugin: next — go build ./... && enable the plugin in 插件中心")
	return nil
}

func findBackendRoot() (string, error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir := wd
	for {
		if _, err := os.Stat(filepath.Join(dir, "plugins", "all", "all.go")); err == nil {
			return dir, nil
		}
		if _, err := os.Stat(filepath.Join(dir, "backend", "plugins", "all", "all.go")); err == nil {
			return filepath.Join(dir, "backend"), nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("cannot find backend root (looked for plugins/all/all.go from %s)", wd)
		}
		dir = parent
	}
}

func titleFromID(id string) string {
	parts := strings.Split(id, "")
	_ = parts
	var b strings.Builder
	upper := true
	for _, r := range id {
		if r == '_' || r == '-' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func exportNameFromID(id string) string {
	return titleFromID(id) + "Page"
}

func renderPluginGo(id, name, pageCode, component, table string, withMigration bool) string {
	var b strings.Builder
	b.WriteString("// Code generated by new-plugin; edit as needed.\n")
	b.WriteString("package " + id + "\n\n")
	if withMigration {
		b.WriteString("import (\n")
		b.WriteString("\t\"embed\"\n")
		b.WriteString("\t\"io/fs\"\n")
		b.WriteString("\t\"net/http\"\n")
		b.WriteString("\t\"path\"\n")
		b.WriteString("\t\"strings\"\n\n")
		b.WriteString("\t\"dragz-admin/backend/internal/app\"\n")
		b.WriteString("\t\"dragz-admin/backend/internal/plugin\"\n")
		b.WriteString(")\n\n")
		b.WriteString("//go:embed migrations/*.sql\nvar migrationFS embed.FS\n\n")
	} else {
		b.WriteString("import (\n")
		b.WriteString("\t\"net/http\"\n\n")
		b.WriteString("\t\"dragz-admin/backend/internal/app\"\n")
		b.WriteString("\t\"dragz-admin/backend/internal/plugin\"\n")
		b.WriteString(")\n\n")
	}
	b.WriteString("// Plugin implements plugin.Plugin")
	if withMigration {
		b.WriteString(" and plugin.Migrator")
	}
	b.WriteString(".\ntype Plugin struct{}\n\n")
	b.WriteString("func (Plugin) Meta() plugin.Meta {\n")
	b.WriteString("\treturn plugin.Meta{\n")
	b.WriteString(fmt.Sprintf("\t\tID:          %q,\n", id))
	b.WriteString(fmt.Sprintf("\t\tName:        %q,\n", name))
	b.WriteString("\t\tVersion:     \"0.1.0\",\n")
	b.WriteString(fmt.Sprintf("\t\tDescription: %q,\n", name+" plugin"))
	b.WriteString("\t\tDependsOn:   []string{\"system\"},\n")
	b.WriteString("\t\tOrder:       100,\n")
	b.WriteString("\t\tBuiltin:     false,\n")
	b.WriteString("\t\tMenus: []plugin.Menu{{\n")
	b.WriteString(fmt.Sprintf("\t\t\tCode:      %q,\n", pageCode))
	b.WriteString(fmt.Sprintf("\t\t\tName:      %q,\n", name))
	b.WriteString(fmt.Sprintf("\t\t\tNameEn:    %q,\n", titleFromID(id)))
	b.WriteString(fmt.Sprintf("\t\t\tRouteName: %q,\n", exportNameFromID(id)))
	b.WriteString(fmt.Sprintf("\t\t\tRoutePath: %q,\n", "/"+id))
	b.WriteString(fmt.Sprintf("\t\t\tComponent: %q,\n", component))
	b.WriteString("\t\t\tIcon:      \"lucide:box\",\n")
	b.WriteString("\t\t\tSort:      900,\n")
	b.WriteString("\t\t}},\n")
	if withMigration {
		b.WriteString(fmt.Sprintf("\t\tDropTables: []string{%q},\n", table))
	}
	b.WriteString("\t}\n}\n\n")
	b.WriteString("func (Plugin) Routes() []plugin.Route {\n")
	b.WriteString("\treturn []plugin.Route{{\n")
	b.WriteString("\t\tMethod:     http.MethodGet,\n")
	b.WriteString(fmt.Sprintf("\t\tPath:       %q,\n", "/api/"+id+"/ping"))
	b.WriteString(fmt.Sprintf("\t\tPermission: %q,\n", id+":ping"))
	b.WriteString(fmt.Sprintf("\t\tMenuCode:   %q,\n", pageCode))
	b.WriteString("\t\tMenuName:   \"连通性检查\",\n")
	b.WriteString("\t\tHandler:    pingHandler,\n")
	b.WriteString("\t}}\n}\n\n")
	if withMigration {
		b.WriteString(`func (Plugin) Migrations() []plugin.Migration {
	entries, err := fs.ReadDir(migrationFS, "migrations")
	if err != nil {
		panic("` + id + `: read embedded migrations: " + err.Error())
	}
	migrations := make([]plugin.Migration, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".sql") {
			continue
		}
		base := strings.TrimSuffix(entry.Name(), ".sql")
		version, migName, found := strings.Cut(base, "_")
		if !found || version == "" {
			panic("` + id + `: migration " + entry.Name() + " must be named <version>_<name>.sql")
		}
		body, err := migrationFS.ReadFile(path.Join("migrations", entry.Name()))
		if err != nil {
			panic("` + id + `: read migration " + entry.Name() + ": " + err.Error())
		}
		migrations = append(migrations, plugin.Migration{Version: version, Name: migName, SQL: string(body)})
	}
	return migrations
}

`)
	}
	b.WriteString(`func pingHandler(*app.Context) http.HandlerFunc {
	return func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json; charset=utf-8")
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte(` + "`" + `{"code":0,"message":"ok","data":{"pong":true,"plugin":"` + id + `"}}` + "`" + `))
	}
}
`)
	return b.String()
}

func patchAllGo(path, id string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	// Normalize to LF while editing; write back LF (Go tools accept it on Windows).
	src := strings.ReplaceAll(string(data), "\r\n", "\n")
	importLine := fmt.Sprintf("\t\"dragz-admin/backend/plugins/%s\"\n", id)
	if strings.Contains(src, "plugins/"+id+"\"") {
		return fmt.Errorf("plugins/all/all.go already imports %s", id)
	}

	importBlock := regexp.MustCompile(`(?s)(import \(\n)(.*?)(\n\))`)
	m := importBlock.FindStringSubmatch(src)
	if m == nil {
		return fmt.Errorf("cannot find import block in %s", path)
	}
	imports := m[2]
	if !strings.HasSuffix(imports, "\n") {
		imports += "\n"
	}
	imports += importLine
	src = importBlock.ReplaceAllString(src, m[1]+imports+m[3])

	marker := "\t\t// scaffold:insert"
	insert := fmt.Sprintf("\t\t%s.Plugin{},\n%s", id, marker)
	if !strings.Contains(src, marker) {
		return fmt.Errorf("%s: missing // scaffold:insert marker", path)
	}
	if strings.Contains(src, id+".Plugin{}") {
		return fmt.Errorf("plugins/all/all.go already registers %s", id)
	}
	src = strings.Replace(src, marker, insert, 1)

	return os.WriteFile(path, []byte(src), 0o644)
}

func scaffoldFrontend(repoRoot, id, exportName, component, name string) error {
	pageDir := filepath.Join(repoRoot, "frontend", "admin", "src", "pages", id)
	if err := os.MkdirAll(pageDir, 0o755); err != nil {
		return err
	}
	page := fmt.Sprintf(`import { Typography } from "antd";
import { useTranslation } from "react-i18next";
import { Page } from "@/components/Page";

/** Scaffolded by new-plugin — replace with real UI. */
export function %s() {
  const { t } = useTranslation();
  return (
    <Page title={t("pages.%s.title")}>
      <Typography.Paragraph>{t("pages.%s.intro")}</Typography.Paragraph>
    </Page>
  );
}
`, exportName, id, id)
	if err := os.WriteFile(filepath.Join(pageDir, "index.tsx"), []byte(page), 0o644); err != nil {
		return err
	}

	pageMapPath := filepath.Join(repoRoot, "frontend", "admin", "src", "router", "page-map.tsx")
	pm, err := os.ReadFile(pageMapPath)
	if err != nil {
		return err
	}
	entry := fmt.Sprintf("  '%s': named(() => import('@/pages/%s'), '%s'),\n", component, id, exportName)
	if bytes.Contains(pm, []byte("'"+component+"'")) {
		return fmt.Errorf("page-map already has %s", component)
	}
	const anchor = "  '/profile/index':"
	if !bytes.Contains(pm, []byte(anchor)) {
		return fmt.Errorf("page-map.tsx: cannot find insertion anchor %q", anchor)
	}
	pm = bytes.Replace(pm, []byte(anchor), []byte(entry+anchor), 1)
	if err := os.WriteFile(pageMapPath, pm, 0o644); err != nil {
		return err
	}

	testPath := filepath.Join(repoRoot, "frontend", "admin", "src", "router", "page-map.test.tsx")
	if testData, err := os.ReadFile(testPath); err == nil {
		s := string(testData)
		if !strings.Contains(s, "'"+component+"'") {
			const needle = "const backendComponents=["
			if i := strings.Index(s, needle); i >= 0 {
				j := strings.Index(s[i:], "];")
				if j > 0 {
					closeAt := i + j
					s = s[:closeAt] + ",'" + component + "'" + s[closeAt:]
					if err := os.WriteFile(testPath, []byte(s), 0o644); err != nil {
						return err
					}
				}
			}
		}
	}

	for _, loc := range []struct {
		file string
		title string
		intro string
	}{
		{"zh.json", name, name + " 插件页面（由 new-plugin 生成）"},
		{"en.json", titleFromID(id), titleFromID(id) + " plugin page (scaffolded by new-plugin)"},
	} {
		locPath := filepath.Join(repoRoot, "frontend", "admin", "src", "locales", loc.file)
		raw, err := os.ReadFile(locPath)
		if err != nil {
			return err
		}
		s := strings.ReplaceAll(string(raw), "\r\n", "\n")
		keyBlock := fmt.Sprintf(`    "%s": {
      "title": %q,
      "intro": %q
    }`, id, loc.title, loc.intro)
		if strings.Contains(s, `"`+id+`": {`) {
			continue
		}
		marker := `"example": {`
		if i := strings.Index(s, marker); i >= 0 {
			rest := s[i:]
			closeIdx := strings.Index(rest, "\n    },\n")
			if closeIdx < 0 {
				return fmt.Errorf("%s: cannot find end of pages.example", loc.file)
			}
			insertAt := i + closeIdx + len("\n    },\n")
			s = s[:insertAt] + keyBlock + ",\n" + s[insertAt:]
		} else if j := strings.Index(s, `"pages": {`); j >= 0 {
			insertAt := j + len(`"pages": {`)
			s = s[:insertAt] + "\n" + keyBlock + "," + s[insertAt:]
		} else {
			return fmt.Errorf("%s: cannot find pages object", loc.file)
		}
		if err := os.WriteFile(locPath, []byte(s), 0o644); err != nil {
			return err
		}
	}
	return nil
}
