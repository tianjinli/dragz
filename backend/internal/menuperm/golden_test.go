// update rewrites the golden file instead of comparing against it.
var update = flag.Bool("update", false, "rewrite testdata/buttons.golden")

// seedMenuIDs mirrors the non-button menus a freshly initialised database
// holds: migrations/001_system_init.sql plus the plugin center page. The test
// is deliberately independent of a live database, so the map is a fixture.
var seedMenuIDs = map[string]uint64{
	"dashboard": 1, "organization": 10,
	"system_user": 11, "system_department": 12, "system_position": 13,
	"system_role": 14, "system_menu": 15,
	"settings": 20, "system_dict": 21, "system_config": 22, "system_storage": 23,
	"system_translation": 24,
	"messages": 30, "system_notice": 31, "my_messages": 32,
	"files": 40, "system_file": 41, "system_file_recycle": 42,
	"security": 50, "system_online": 51, "system_token": 52,
	"system_login_log": 53, "system_operation_log": 54, "system_error_log": 55,
	"tools": 60, "system_job": 61, "system_webhook": 62, "system_cache": 63,
	"system_plugin": 87,
	"example_page":  1000,
}

// TestGoldenButtons pins code|name|parent for every declared permission code.
// A new route that resolves to no page, or to the wrong page, fails here
// instead of surfacing as a button hanging off the wrong menu at runtime.
func TestGoldenButtons(t *testing.T) {
	registry, err := kernel.Build(all.All())
	if err != nil {
		t.Fatalf("build registry: %v", err)
	}

	builtin := make(map[string]bool)
	for _, meta := range registry.Metas() {
		builtin[meta.ID] = true
	}

	routes := make([]menuperm.Route, 0, len(registry.Routes()))
	for _, bound := range registry.Routes() {
		codes := make([]string, 0, len(bound.Route.AnyOf)+1)
		if bound.Route.Permission != "" {
			codes = append(codes, bound.Route.Permission)
		}
		codes = append(codes, bound.Route.AnyOf...)
		routes = append(routes, menuperm.Route{
			PluginID: bound.PluginID,
			Codes:    codes,
			MenuCode: bound.Route.MenuCode,
			MenuName: bound.Route.MenuName,
			Method:   bound.Route.Method,
			Path:     bound.Route.Path,
			Builtin:  builtin[bound.PluginID],
		})
	}

	buttons, unresolved := menuperm.Build(routes, seedMenuIDs)
	for _, item := range unresolved {
		if item.Builtin {
			t.Errorf("core permission %q (plugin %q) resolves to no menu page", item.Code, item.PluginID)
		}
	}
	if t.Failed() {
		t.FailNow()
	}

	lines := make([]string, 0, len(buttons)+1)
	lines = append(lines, "# buttons.golden - generated by go test ./internal/menuperm -update")
	lines = append(lines, "# 列: CODE|NAME|NAME_EN|PARENT_CODE|METHOD|PATH")
	for _, button := range buttons {
		lines = append(lines, strings.Join([]string{
			button.Code, button.Name, button.NameEn, button.ParentKey, button.Method, button.Path,
		}, "|"))
	}
	got := strings.Join(lines, "\n") + "\n"

	path := filepath.Join("testdata", "buttons.golden")
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatalf("mkdir testdata: %v", err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (run go test ./internal/menuperm -update to create it): %v", err)
	}
	if string(want) != got {
		t.Errorf("buttons golden drifted; rerun with -update and review the diff\n--- got ---\n%s", got)
	}
}
